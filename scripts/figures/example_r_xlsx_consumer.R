# Example R consumer of mlsurv's xlsx export.
#
# This script reads an exported results workbook by sheet name and builds an
# AUC(t) plot. It is kept in the repo as the canonical example of how an
# external R (or Galaxy) consumer reads mlsurv's xlsx export, and it doubles as
# the fixture for tests/test_r_consumer_contract.py: that test parses the
# sheet-name string literals in the read_excel() calls below and asserts they
# match the sheet names the producer (mlsurv.learner._export) actually
# generates. If you rename a producer-side key, update both this script and
# that test in the same commit.
#
# The input workbook lives under examples/output/ (a local, untracked
# artifact regenerated by examples/vignette_07_immunotherapy_case_study.ipynb),
# so the plot itself only renders on a machine that has regenerated it. The
# sheet-name contract the test guards does not depend on it.

library("readxl")
library("dplyr")
library("tidyr")
library("ggplot2")

data_dir <- "examples/output/vig7"
xlsx_path <- file.path(data_dir, "results_OS.xlsx")

# ── Read sheets ──────────────────────────────────────────────────────
cat("Reading results_OS.xlsx...\n")

cohort <- read_excel(xlsx_path, sheet = "subpopulation_Cancer Type_cohor")
auc_t <- read_excel(xlsx_path, sheet = "subpopulation_Cancer Type_auc_t")
boot_ml <- read_excel(xlsx_path, sheet = "eval_bootstrap_subpopulation_au")
boot_bench <- read_excel(xlsx_path, sheet = "benchmark_eval_bootstrap_subpop")

# ── Identify top 3 cancer types by sample size ──────────────────────
top3 <- cohort |>
  arrange(desc(n_samples)) |>
  slice_head(n = 3)

top3_names <- top3$subpopulation
top3_labels <- paste0(top3$subpopulation, " (n=", top3$n_samples, ")")
names(top3_labels) <- top3_names

cat("Top 3 cancer types:", paste(top3_labels, collapse = ", "), "\n")

# ── Point estimates: CoxNet, LORIS, TMB ─────────────────────────────
points_main <- auc_t |>
  filter(
    subpopulation %in% top3_names,
    model_type %in% c("coxnet", "LORIS", "TMB")
  ) |>
  drop_na(auc) |>
  select(subpopulation, model_type, eval_time, auc)

# ── Point estimates: PD-L1 (median of bootstrap, NSCLC only) ────────
points_pdl1 <- boot_bench |>
  filter(subpopulation == "NSCLC", model_type == "PD-L1") |>
  drop_na(auc) |>
  group_by(subpopulation, model_type, eval_time) |>
  summarise(auc = median(auc), .groups = "drop")

points_all <- bind_rows(points_main, points_pdl1)

# ── 95% CIs: CoxNet (ML bootstrap) + LORIS, TMB, PD-L1 (benchmark) ─
ci_all <- bind_rows(
    boot_ml |> filter(subpopulation %in% top3_names, model_type == "coxnet"),
    boot_bench |> filter(subpopulation %in% top3_names,
                         model_type %in% c("LORIS", "TMB", "PD-L1"))
  ) |>
  drop_na(auc) |>
  group_by(subpopulation, model_type, eval_time) |>
  summarise(
    ci_lower = quantile(auc, 0.025),
    ci_upper = quantile(auc, 0.975),
    .groups = "drop"
  )

# ── Join point estimates + CIs ──────────────────────────────────────
plot_data <- points_all |>
  left_join(ci_all, by = c("subpopulation", "model_type", "eval_time"))

# ── Display labels and ordering ─────────────────────────────────────
model_labels <- c(
  "coxnet" = "CoxNet (ML)",
  "LORIS" = "LORIS",
  "TMB" = "TMB",
  "PD-L1" = "PD-L1"
)
model_colors <- c(
  "CoxNet (ML)" = "#2166AC",
  "LORIS" = "#B2182B",
  "TMB" = "#4DAF4A",
  "PD-L1" = "#FF7F00"
)

plot_data <- plot_data |>
  mutate(
    model_label = model_labels[model_type],
    facet_label = factor(top3_labels[subpopulation], levels = top3_labels)
  )

# ── Plot ────────────────────────────────────────────────────────────
p <- ggplot(plot_data, aes(x = eval_time, y = auc, color = model_label,
                           fill = model_label)) +
  geom_ribbon(aes(ymin = ci_lower, ymax = ci_upper),
              alpha = 0.15, color = NA) +
  geom_line(linewidth = 0.8) +
  geom_hline(yintercept = 0.5, linetype = "dashed", color = "grey50",
             linewidth = 0.4) +
  facet_wrap(~facet_label, nrow = 1) +
  scale_color_manual(values = model_colors) +
  scale_fill_manual(values = model_colors) +
  scale_y_continuous(limits = c(0, 1), breaks = seq(0, 1, 0.25)) +
  labs(
    x = "Time (months)",
    y = "AUC(t)",
    color = NULL,
    fill = NULL
  ) +
  theme_minimal(base_size = 11) +
  theme(
    legend.position = "bottom",
    legend.key.width = unit(1.2, "cm"),
    strip.text = element_text(face = "bold", size = 10),
    panel.grid.minor = element_blank(),
    axis.title = element_text(size = 10),
    plot.margin = margin(10, 15, 10, 10)
  )

# ── Save ────────────────────────────────────────────────────────────
out_dir <- "scripts/figures"
ggsave(file.path(out_dir, "auct_top3_cancers_OS.pdf"), p,
       width = 10, height = 3.5)
ggsave(file.path(out_dir, "auct_top3_cancers_OS.png"), p,
       width = 10, height = 3.5, dpi = 300)

cat("Saved to", out_dir, "\n")
