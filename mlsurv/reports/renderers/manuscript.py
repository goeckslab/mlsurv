"""Manuscript-prep markdown renderer for pandoc-compatible output."""

import html
import re
from html.parser import HTMLParser
from pathlib import Path
from typing import Any, Dict, List, Optional

from mlsurv.reports.renderers.markdown import MarkdownRenderer


class _HTMLTableParser(HTMLParser):
    """Lightweight parser converting an HTML table to a markdown pipe table."""

    def __init__(self):
        super().__init__()
        self.rows: List[List[str]] = []
        self._current_row: List[str] = []
        self._in_cell: bool = False
        self._cell_parts: List[str] = []
        self._skip_depth: int = 0

    def handle_starttag(self, tag, attrs):
        if tag in ("script", "style"):
            self._skip_depth += 1
            return
        if self._skip_depth:
            return
        if tag == "tr":
            self._current_row = []
        elif tag in ("td", "th"):
            self._in_cell = True
            self._cell_parts = []
        elif tag == "br" and self._in_cell:
            self._cell_parts.append(" ")

    def handle_endtag(self, tag):
        if tag in ("script", "style") and self._skip_depth > 0:
            self._skip_depth -= 1
            return
        if self._skip_depth:
            return
        if tag in ("td", "th") and self._in_cell:
            self._in_cell = False
            self._current_row.append("".join(self._cell_parts).strip())
        elif tag == "tr" and self._current_row:
            self.rows.append(self._current_row)

    def handle_data(self, data):
        if self._skip_depth:
            return
        if self._in_cell:
            self._cell_parts.append(data)


def _pad_row(row: List[str], n_cols: int) -> List[str]:
    """Pad *row* with empty strings to reach *n_cols*."""
    return row + [""] * (n_cols - len(row))


def _format_pipe_table(rows: List[List[str]]) -> str:
    """Format parsed table rows as a markdown pipe table.

    The first row is treated as the header.
    """
    if not rows:
        return ""

    header = rows[0]
    body = rows[1:]
    n_cols = max(len(r) for r in rows)

    header = _pad_row(header, n_cols)
    widths = [max(3, len(cell)) for cell in header]
    for row in body:
        for i, cell in enumerate(_pad_row(row, n_cols)):
            widths[i] = max(widths[i], len(cell))

    def _fmt(row: List[str]) -> str:
        cells = [cell.ljust(w) for cell, w in zip(_pad_row(row, n_cols), widths)]
        return "| " + " | ".join(cells) + " |"

    lines = [_fmt(header)]
    lines.append("|" + "|".join("-" * (w + 2) for w in widths) + "|")
    for row in body:
        lines.append(_fmt(row))
    return "\n".join(lines)


def _html_table_to_markdown(html_table: str) -> str:
    """Convert an HTML ``<table>`` to a markdown pipe table."""
    parser = _HTMLTableParser()
    parser.feed(html_table)
    return _format_pipe_table(parser.rows)


# HTML inline tags and their markdown equivalents.
# Each entry is (html_tag, markdown_wrapper).
_INLINE_TAG_MAP = [
    ("strong", "**"),
    ("summary", "**"),
    ("em", "*"),
    ("code", "`"),
]


class ManuscriptRenderer(MarkdownRenderer):
    """Render report content to pandoc-compatible manuscript markdown.

    Produces clean markdown with:
    - YAML front matter for pandoc metadata
    - HTML artifact stripping (``<details>``, ``<div>``, ``<button>``, etc.)
    - Figure cross-references (``{#fig:id}``)
    - Page breaks (``\\newpage``) between sections
    - Static PNG figures via kaleido

    Parameters
    ----------
    output_path : str or Path
        Path to output markdown file.
    title : str
        Report title.
    """

    def render(
        self,
        sections: List[Dict[str, Any]],
        metadata: Optional[dict] = None,
    ) -> str:
        """Render all sections to pandoc-ready manuscript markdown."""
        lines: List[str] = []

        lines.extend(self._build_front_matter(metadata))

        for section in sections:
            lines.append("\\newpage")
            lines.append("")
            lines.append(f"## {section['title']}")
            lines.append("")
            lines.append(self._prepare_markdown(section["markdown"]))
            lines.append("")

            for tab in section.get("tabs") or []:
                lines.append(f"### {tab.get('title', 'Tab')}")
                lines.append("")
                lines.append(self._prepare_markdown(tab.get("markdown", "")))
                lines.append("")

        lines.append("---")
        lines.append("*Generated by mlsurv*")

        return "\n".join(lines)

    def _prepare_markdown(self, markdown: str) -> str:
        """Strip HTML artifacts and add figure cross-references."""
        markdown = self._clean_html_artifacts(markdown)
        return self._add_figure_cross_refs(markdown)

    # ------------------------------------------------------------------
    # YAML front matter
    # ------------------------------------------------------------------

    @staticmethod
    def _yaml_escape(text: str) -> str:
        """Escape a string for use in a YAML double-quoted value."""
        return text.replace("\\", "\\\\").replace('"', '\\"')

    def _build_front_matter(self, metadata: Optional[dict]) -> List[str]:
        """Build pandoc YAML front-matter block."""
        safe_title = self._yaml_escape(self.title)
        lines = ["---", f'title: "{safe_title}"']

        if metadata:
            if "timestamp" in metadata:
                date_str = metadata["timestamp"].split(" ")[0]
                lines.append(f'date: "{date_str}"')

            # Build abstract from dataset dimensions
            abstract_fields = [
                ("version", lambda v: f"mlsurv v{v}"),
                ("n_samples", lambda v: f"{v:,} samples"),
                ("n_features", lambda v: f"{v:,} features"),
                ("n_events", lambda v: f"{v:,} events"),
            ]
            parts = [
                fmt(metadata[key])
                for key, fmt in abstract_fields
                if key in metadata
            ]
            if parts:
                abstract = self._yaml_escape(" | ".join(parts))
                lines.append(f'abstract: "{abstract}"')

        lines.append("---")
        lines.append("")
        return lines

    # ------------------------------------------------------------------
    # HTML artifact stripping
    # ------------------------------------------------------------------

    def _clean_html_artifacts(self, markdown: str) -> str:
        """Strip HTML artifacts from section markdown for pandoc compatibility."""
        # 1. Remove RAW_HTML markers (keep content between them)
        markdown = re.sub(r"<!--\s*/?\s*MLSURV_RAW_HTML\s*-->", "", markdown)

        # 2. Handle <details> blocks
        markdown = self._strip_details_blocks(markdown)

        # 2b. Safety-net: remove any unclosed <details> tags
        markdown = re.sub(r"</?details[^>]*>", "", markdown)

        # 3. Callout divs (warning + info) -> blockquotes
        markdown = self._convert_callout_warnings(markdown)

        # 4. Figure placeholders -> image refs (attribute-order agnostic).
        #    data-figure carries a bare basename, but save_figures() writes the
        #    PNG into images/, so point the ref at the real file location;
        #    otherwise the markdown link is broken.
        def _figure_ref(match: "re.Match[str]") -> str:
            name = match.group(1)
            if "/" not in name:
                name = f"images/{name}"
            return f"![]({name})"

        markdown = re.sub(
            r'<div\s+[^>]*data-figure="([^"]+)"[^>]*>\s*</div>',
            _figure_ref,
            markdown,
        )

        # 5. Prediction table scroll wrappers -> keep inner content
        markdown = re.sub(
            r'<div\s+class="prediction-table-scroll"[^>]*>', "", markdown
        )

        # 6. <button ...>...</button> elements
        markdown = re.sub(r"<button[^>]*>.*?</button>", "", markdown, flags=re.DOTALL)

        # 7. HTML tables -> markdown tables
        markdown = self._convert_html_tables(markdown)

        # 8. Remaining <div>...</div> and stray </div>
        markdown = re.sub(r"</?div[^>]*>", "", markdown)

        # 9. <br> / <br/> / <br /> -> newlines
        markdown = re.sub(r"<br\s*/?\s*>", "\n", markdown)

        # 10. Inline HTML tags -> markdown equivalents
        for tag, wrap in _INLINE_TAG_MAP:
            markdown = re.sub(
                rf"<{tag}>(.*?)</{tag}>", rf"{wrap}\1{wrap}", markdown,
                flags=re.DOTALL,
            )

        # 11. Remaining stray tags (span, p, pre, summary, section, label,
        #     input, etc.). label/input come from interactive feature-table
        #     toggles that have no meaning in static markdown; drop the tags but
        #     keep their visible text (the model and column names).
        markdown = re.sub(
            r"</?(?:span|p|pre|summary|section|label|input)[^>]*>", "", markdown
        )

        # 12. HTML entities -> Unicode
        markdown = html.unescape(markdown)

        # 13. Collapse excessive blank lines (max 2)
        markdown = re.sub(r"\n{3,}", "\n\n", markdown)

        return markdown.strip()

    def _strip_details_blocks(self, markdown: str) -> str:
        """Expand or drop ``<details>`` blocks.

        BibTeX blocks are dropped entirely; other details blocks are
        expanded inline with their summary as a bold heading.
        """
        def _replace_details(match: re.Match) -> str:
            inner = match.group(1)
            # Drop BibTeX blocks entirely
            if "BibTeX" in inner and "```" in inner:
                return ""
            # Strip <summary>...</summary> and convert to bold heading
            summary_match = re.search(
                r"<summary>(.*?)</summary>", inner, re.DOTALL
            )
            if summary_match:
                heading = summary_match.group(1).strip()
                inner = inner[: summary_match.start()] + inner[summary_match.end():]
                return f"\n**{heading}**\n{inner.strip()}\n"
            return inner.strip()

        # Handle nested details by processing innermost first, repeatedly
        prev = None
        for _ in range(50):
            prev = markdown
            markdown = re.sub(
                r"<details[^>]*>\s*(.*?)\s*</details>",
                _replace_details,
                markdown,
                flags=re.DOTALL,
            )
            if prev == markdown:
                break
        return markdown

    def _convert_callout_warnings(self, markdown: str) -> str:
        """Convert callout divs (warning and info) to blockquotes."""
        def _replace_callout(match: re.Match) -> str:
            inner = re.sub(r"<[^>]+>", "", match.group(1)).strip()
            quoted = "\n".join(f"> {line}" for line in inner.splitlines() if line.strip())
            return f"> **Warning:**\n{quoted}"

        return re.sub(
            r'<div\s+[^>]*class="mlsurv-callout-(?:warning|info)"[^>]*>'
            r'\s*(.*?)\s*</div>',
            _replace_callout,
            markdown,
            flags=re.DOTALL,
        )

    def _convert_html_tables(self, markdown: str) -> str:
        """Convert remaining ``<table>...</table>`` blocks to pipe tables."""
        def _replace_table(match: re.Match) -> str:
            return _html_table_to_markdown(match.group(0)) or match.group(0)

        return re.sub(
            r"<table[^>]*>.*?</table>",
            _replace_table,
            markdown,
            flags=re.DOTALL,
        )

    # ------------------------------------------------------------------
    # Figure cross-references
    # ------------------------------------------------------------------

    @staticmethod
    def _add_figure_cross_refs(markdown: str) -> str:
        """Add pandoc-crossref identifiers to image references."""
        def _add_ref(match: re.Match) -> str:
            stem = Path(match.group(2)).stem
            return f"{match.group(0)}{{#fig:{stem}}}"

        return re.sub(r"!\[([^\]]*)\]\(([^)]+)\)", _add_ref, markdown)
