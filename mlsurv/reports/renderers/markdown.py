"""Markdown renderer for report generation."""

import re
from pathlib import Path
from typing import Any, Dict, List, Optional, Set

from mlsurv.viz._palettes import MANUSCRIPT_DEFAULTS
from mlsurv.reports.renderers._figures import (
    _bind_var,
    _data_accessor_lines,
    _find_matching_figure,
    _resolve_data_label,
)


# Matches a markdown image reference, capturing the path so we can check that
# its file actually exists on disk. Handles both ``images/foo.png`` (literal
# section refs) and ``foo.png`` (bare basename from data-figure conversion), an
# optional ``"title"`` after the path, and an optional trailing pandoc cross-ref
# attribute block like ``{#fig:foo}`` so a stripped figure leaves no dangling ref.
_IMAGE_REF_RE = re.compile(
    r'!\[(?P<alt>[^\]]*)\]'      # ![alt]
    r'\((?P<path>[^)\s]+)'       # (path  (no spaces or closing paren)
    r'(?:\s+"[^"]*")?\)'         # optional "title" then )
    r'(?P<attr>\{[^}]*\})?'      # optional {#fig:...}
)

# Shown in place of an image reference whose PNG was never written (export
# skipped on timeout or engine error), so the report has no broken image link.
_MISSING_FIGURE_PLACEHOLDER = "*Figure unavailable: static image export failed.*"


class MarkdownRenderer:
    """
    Render report content to Markdown format.

    Creates a markdown file with embedded images. Images are saved as PNG
    files in an images/ subdirectory using kaleido for static export.

    Parameters
    ----------
    output_path : str or Path
        Path to output markdown file.
    title : str
        Report title.
    """

    def __init__(self, output_path: str, title: str = "Survival Analysis Report"):
        self.output_path = Path(output_path)
        self.title = title

        # Ensure output directory exists
        self.output_path.parent.mkdir(parents=True, exist_ok=True)

        # Images directory
        self.images_dir = self.output_path.parent / "images"

    def render(self, sections: List[Dict[str, Any]], metadata: Optional[dict] = None) -> str:
        """
        Render all sections to markdown.

        Parameters
        ----------
        sections : list
            List of section dictionaries with 'title', 'markdown', 'figures' keys.
        metadata : dict, optional
            Report metadata (version, timestamp, dimensions) for the header.

        Returns
        -------
        str
            Complete markdown content.
        """
        lines = []

        # Title
        lines.append(f"# {self.title}")
        lines.append("")

        # Metadata line
        if metadata:
            meta_str = _render_md_metadata(metadata)
            if meta_str:
                lines.append(meta_str)
                lines.append('')

        # Table of contents
        lines.append("## Table of Contents")
        lines.append("")
        for i, section in enumerate(sections, 1):
            anchor = section['title'].lower().replace(' ', '-').replace('(', '').replace(')', '')
            lines.append(f"{i}. [{section['title']}](#{anchor})")
        lines.append("")

        # Sections
        for section in sections:
            lines.append(f"## {section['title']}")
            lines.append("")

            lines.append(section['markdown'])
            lines.append("")

            tabs = section.get('tabs') or []
            for tab in tabs:
                tab_title = tab.get('title', 'Tab')
                tab_markdown = tab.get('markdown', '')
                lines.append(f"### {tab_title}")
                lines.append("")
                lines.append(tab_markdown)
                lines.append("")

            # Consolidated programmatic access dropdown
            access_md = self._render_consolidated_access(section)
            if access_md:
                lines.append(access_md)
                lines.append("")

        # Footer
        lines.append("---")
        lines.append("*Generated by mlsurv*")

        return '\n'.join(lines)

    def save_figures(self, figures: List[tuple]) -> Set[str]:
        """
        Save figures as PNG files.

        Parameters
        ----------
        figures : list
            List of (filename, plotly.Figure) tuples.

        Returns
        -------
        set of str
            Basenames of figures that were not written (export failed, or
            skipped after a timeout). Pass to ``strip_missing_figures`` so the
            body drops their references. Empty when every figure exported.
        """
        failed: Set[str] = set()
        if not figures:
            return failed

        # Create images directory
        self.images_dir.mkdir(parents=True, exist_ok=True)

        export_scale = MANUSCRIPT_DEFAULTS["export_scale"]

        from mlsurv.logging_utils import get_logger, log_exception
        from mlsurv.reports._figure_export import (
            FigureExportTimeout,
            write_image_safe,
        )
        from mlsurv._warnings import SuggestionWarning
        _logger = get_logger("reports.renderers.markdown")

        for index, (filename, fig) in enumerate(figures):
            filepath = self.images_dir / filename
            try:
                # Use kaleido for static export at manuscript quality.
                # Bounded so a stalled browser can't wedge the whole report.
                write_image_safe(fig, filepath, scale=export_scale)
            except FigureExportTimeout as e:
                # One timeout means kaleido/Chrome is wedged; the remaining
                # figures would each block for the full timeout too. Skip them
                # so the report finishes instead of blocking N x timeout.
                # This figure plus all the ones we won't reach are unwritten.
                failed.update(fn for fn, _ in figures[index:])
                skipped = len(figures) - index
                log_exception(
                    _logger, e, f"save_figures: {filename}",
                    warn_user=True,
                    category=SuggestionWarning,
                    user_message=(
                        f"Static-image export timed out on {filename} "
                        "(kaleido/Chrome unresponsive); skipping "
                        f"{skipped} remaining figure(s). "
                        "Report will be generated without these images."
                    ),
                )
                break
            except ValueError as e:
                failed.add(filename)
                if "kaleido" in str(e).lower():
                    log_exception(
                        _logger, e, f"save_figures: {filename}",
                        warn_user=True,
                        user_message=(
                            f"Could not save figure {filename}: kaleido engine error. "
                            "Try reinstalling kaleido: pip install --upgrade kaleido"
                        ),
                    )
                else:
                    log_exception(
                        _logger, e, f"save_figures: {filename}",
                        warn_user=True,
                        user_message=f"Could not save figure {filename}: {e}",
                    )
            except (OSError, ImportError, RuntimeError) as e:
                failed.add(filename)
                log_exception(
                    _logger, e, f"save_figures: {filename}",
                    warn_user=True,
                    user_message=(
                        f"Could not save figure {filename}: {e}. "
                        "Report will be generated without this image."
                    ),
                )

        return failed

    def strip_missing_figures(
        self, content: str, failed: Optional[Set[str]] = None
    ) -> str:
        """
        Replace image references to missing PNGs with a placeholder note.

        A skipped figure (export timeout or engine error) leaves a markdown
        ``![](images/foo.png)`` reference pointing at a file that was never
        written, which renders as a broken image. This rewrites each such
        reference to a short placeholder.

        A reference is replaced when its basename is in ``failed`` OR its PNG is
        absent or empty on disk. The ``failed`` set catches a figure the
        renderer knows was skipped this run even when a stale PNG from an
        earlier run still sits in the images directory (which is not cleaned
        between runs). The on-disk check additionally catches any other cause,
        including a truncated or zero-byte export.

        Parameters
        ----------
        content : str
            Rendered markdown body.
        failed : set of str, optional
            Basenames ``save_figures`` reported as not written. Treated as
            authoritative: anything listed here is always replaced.

        Returns
        -------
        str
            The body with references to missing figures replaced.
        """
        def _is_missing(basename: str) -> bool:
            if failed and basename in failed:
                return True
            path = self.images_dir / basename
            try:
                return not (path.exists() and path.stat().st_size > 0)
            except OSError:
                return True

        def _replace(match: "re.Match[str]") -> str:
            basename = Path(match.group("path")).name
            if _is_missing(basename):
                return _MISSING_FIGURE_PLACEHOLDER
            return match.group(0)

        return _IMAGE_REF_RE.sub(_replace, content)

    def write(self, content: str) -> Path:
        """
        Write markdown content to file.

        Parameters
        ----------
        content : str
            Markdown content to write.

        Returns
        -------
        Path
            Path to written file.
        """
        self.output_path.write_text(content, encoding='utf-8')
        return self.output_path

    @staticmethod
    def _render_consolidated_access(section: Dict[str, Any]) -> str:
        """Render a consolidated programmatic-access dropdown in markdown."""
        section_name = section.get('section_name', '')
        figure_info_list = section.get('figure_info', [])
        data_keys = section.get('data_keys', [])
        data_info_list = section.get('data_info') or []

        if not section_name:
            return ""

        data_info_map = {di.data_key: di for di in data_info_list}

        figure_parts = (
            _render_md_figure_items(figure_info_list)
            if figure_info_list else []
        )
        all_data_keys = list(dict.fromkeys(data_keys))
        data_parts = (
            _render_md_data_items(all_data_keys, data_info_map, figure_info_list)
            if all_data_keys else []
        )

        if not figure_parts and not data_parts:
            return ""

        parts = [
            "<details>",
            "<summary>Programmatic Access</summary>",
            "",
            *figure_parts,
            *data_parts,
            "</details>",
        ]
        return "\n".join(parts)


