def _render_md_figure_items(figure_info_list):
    """Build markdown lines for the Figures block in the access dropdown.

    Mirrors the HTML renderer: only figures with a runnable ``learner_code``
    get an entry (reproduce via ``learner.plot_*`` + ``fig.write_image``).
    Returns ``[]`` when no figure is reproducible.
    """
    items = []
    for info in figure_info_list:
        if not info.learner_code and not info.standalone_import:
            continue
        items.append(f"*{info.title}*")
        items.append("")
        items.append("```python")
        if info.learner_code:
            items.append(_bind_var(info.learner_code, 'fig'))
            if info.standalone_import:
                items.append(info.standalone_import)
            items.append(f"fig.write_image('{info.figure_id}.svg')")
        else:
            # Import-only pointer: nothing binds ``fig`` to export.
            items.append(info.standalone_import)
        items.append("```")
        items.append("")
    if not items:
        return []
    return ["**Figures:**", "", *items]


def _render_md_data_items(data_keys, data_info_map, figure_info_list):
    """Build markdown lines for the Data block in the access dropdown.

    Mirrors the HTML renderer: only data keys reachable through a
    learner/results accessor get an entry (no unreachable ``report.data``).
    Returns ``[]`` when no key is reachable.
    """
    items = []
    for dk in data_keys:
        di = data_info_map.get(dk)
        fig_match = _find_matching_figure(figure_info_list, dk)

        lines = _data_accessor_lines(dk, di, fig_match)
        if not lines:
            continue

        items.append(f"*{_resolve_data_label(dk, di, fig_match)}*")
        items.append("")
        items.append("```python")
        items.extend(lines)
        items.append("```")
        items.append("")
    if not items:
        return []
    return ["**Data:**", "", *items]


def _render_md_metadata(metadata: dict) -> str:
    """Build the metadata summary line from a metadata dictionary."""
    parts = []
    if 'version' in metadata:
        parts.append(f'mlsurv v{metadata["version"]}')
    if 'timestamp' in metadata:
        parts.append(metadata['timestamp'])
    if 'n_samples' in metadata:
        parts.append(f'{metadata["n_samples"]:,} samples')
    if 'n_features' in metadata:
        parts.append(f'{metadata["n_features"]:,} features')
    if 'n_events' in metadata:
        parts.append(f'{metadata["n_events"]:,} events')
    return f'*{" | ".join(parts)}*' if parts else ""
