"""StudyMixin - Optuna study listing, export, and reload."""

from __future__ import annotations

import warnings
from typing import TYPE_CHECKING

from .._warnings import SuggestionWarning
from ..tuning import list_studies, export_study as _export_study
from ..tuning.studies import _resolve_study

if TYPE_CHECKING:
    from mlsurv.learner._core import SurvivalLearner


def _resolve_tuned_model(state, model):
    """Resolve model input to a (model_name, model_result) tuple.

    Shared by export_study and reload_study.

    Parameters
    ----------
    state : LearnerState
    model : str, ModelResult, or None

    Returns
    -------
    tuple of (model_name: str or None, model_result: ModelResult or None)
        When *model* is a string, ``model_result`` is ``None`` — the
        caller must resolve via ``_lookup_model_by_name``.
    """
    if model is None:
        tuned = [(name, r) for name, r in state.models.items() if r.is_tuned]
        if not tuned:
            raise ValueError("No tuned models found. Run tune() first.")
        return tuned[-1]
    if isinstance(model, str):
        return model, None  # caller resolves via _lookup_model_by_name
    if not hasattr(model, 'is_tuned'):
        raise TypeError(
            f"Expected model name (str) or ModelResult, "
            f"got {type(model).__name__}."
        )
    return getattr(model, 'name', None), model


class StudyMixin:
    """Mixin for Optuna study listing, export, and reload."""

    @property
    def experiment_path(self: SurvivalLearner):
        """
        Current experiment directory path.

        Returns
        -------
        Path or None
            Full path to the experiment directory, or None if
            ``experiment_name`` has not been set.
        """
        if self._state.experiment_name is None:
            return None
        from ..tuning import DEFAULT_STORAGE_BASE
        return DEFAULT_STORAGE_BASE / self._state.experiment_name

    def list_studies(self: SurvivalLearner, storage=None):
        """
        List Optuna studies for this learner's experiment.

        Scoped to this learner's ``experiment_name`` (set via
        ``setup(experiment_name=...)`` or auto-generated by the first tuning
        run). For a global view across all experiments, call the module-level
        ``mlsurv.tuning.list_studies()`` instead.

        Parameters
        ----------
        storage : str, optional
            Optuna storage URL (e.g. 'postgresql://user:pass@host:port/db'). If
            given, studies are read from the database; otherwise local SQLite
            files under ./optuna_studies/ are scanned.

        Returns
        -------
        list
            Studies belonging to this experiment. In file mode, a list of
            study filenames (e.g. ['rsf_study.db', 'gbsa_study.db']). In
            storage mode, a list of study-info dicts. Empty if no experiment
            name is set or no studies exist yet.
        """
        name = self._state.experiment_name
        if name is None:
            return []
        return list_studies(storage=storage).get(name, [])

    def export_study(self: SurvivalLearner, model=None, *, path=None, format=None):
        """Export Optuna tuning history for a model to CSV or JSON.

        Parameters
        ----------
        model : str or ModelResult, optional
            Model name or result. If None, uses the most recently tuned model.
        path : str or Path, optional
            Output file path. If None, returns data without writing.
        format : {'csv', 'json'}, optional
            Output format. Inferred from path extension if not given.

        Returns
        -------
        dict
            Dictionary with 'trials' (list of dicts) and 'metadata' (dict).

        Raises
        ------
        ValueError
            If no tuned models exist, the named model has not been tuned,
            or the study cannot be located in memory or on disk.
        TypeError
            If ``model`` is not a string, ModelResult, or None.
        """
        model_name, model_result = _resolve_tuned_model(self._state, model)
        if model_result is None:
            # model was a string — look it up
            model_result = self._lookup_model_by_name(model_name)
            if not model_result.is_tuned:
                raise ValueError(
                    f"Model '{model_name}' has not been tuned. Run tune('{model_name}') first."
                )

        # Prefer in-memory study if available
        in_memory_study = getattr(model_result, 'optuna_study', None)
        if in_memory_study is not None:
            return _export_study(study=in_memory_study, path=path, format=format)

        # Fall back to loading from storage
        model_name = getattr(model_result, 'name', None)
        if model_name and self._state.experiment_name:
            return _export_study(
                experiment_name=self._state.experiment_name,
                model_name=model_name,
                path=path, format=format,
            )

        raise ValueError(
            "Cannot locate study: no in-memory study and no experiment_name/model_name."
        )

    def reload_study(self: SurvivalLearner, model=None):
        """Reload Optuna study from disk after load_learner().

        After ``save_learner()`` / ``load_learner()``, the Optuna Study object
        is ``None`` (stripped during pickling to avoid large serialization).
        This method restores it from the SQLite database on disk so you can
        use ``optuna.visualization`` or inspect trial history interactively.

        Parameters
        ----------
        model : str or ModelResult, optional
            Model to reload study for. If None, uses the most recently tuned
            model.

        Returns
        -------
        optuna.Study
            The restored study object (also assigned back to
            ``model_result.optuna_study``).

        Raises
        ------
        ValueError
            If no tuned models exist, the named model has not been tuned,
            or the study cannot be located on disk.
        FileNotFoundError
            If the study database file does not exist.
        TypeError
            If ``model`` is not a string, ModelResult, or None.
        """
        # Resolve model → ModelResult
        model_name, model_result = _resolve_tuned_model(self._state, model)
        if model_result is None:
            # model was a string — look it up
            model_result = self._lookup_model_by_name(model_name)
            if not model_result.is_tuned:
                raise ValueError(
                    f"Model '{model_name}' has not been tuned. "
                    f"Run tune('{model_name}') first."
                )
        elif not model_result.is_tuned:
            raise ValueError(
                "The provided ModelResult has not been tuned. "
                "Run tune() first."
            )

        # Return existing study if already loaded
        existing = getattr(model_result, 'optuna_study', None)
        if existing is not None:
            return existing

        # Resolve experiment_name (fall back to study metadata)
        experiment_name = self._state.experiment_name
        meta = getattr(model_result, '_optuna_study_meta', None)

        if experiment_name is None and meta is not None:
            study_name = meta.get('study_name')
            if study_name and '/' in study_name:
                experiment_name = study_name.rsplit('/', 1)[0]

        if experiment_name is None or model_name is None:
            raise ValueError(
                "Cannot locate study: no experiment_name on learner and "
                "no study metadata on model result. The study database "
                "path cannot be determined."
            )

        # Load study from disk
        study = _resolve_study(
            study=None, study_name=None, storage=None,
            experiment_name=str(experiment_name),
            model_name=model_name, base_dir=None,
        )

        # Warn if trial count on disk diverges from saved metadata
        if meta is not None:
            disk_n_trials = len(study.trials)
            meta_n_trials = meta.get('n_trials')
            if meta_n_trials is not None and disk_n_trials != meta_n_trials:
                warnings.warn(
                    f"Study on disk has {disk_n_trials} trials but learner "
                    f"metadata recorded {meta_n_trials} trials. The study "
                    f"may have been modified since save_learner().",
                    SuggestionWarning,
                    stacklevel=2,
                )

        model_result.optuna_study = study
        return study
